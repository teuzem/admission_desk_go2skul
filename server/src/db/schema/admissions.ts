export const applications = pgTable(
  'applications',
  {
    id: pk(),
    agentId: uuid('agent_id').notNull().references(() => profiles.id, { onDelete: 'cascade' }),
    studentId: uuid('student_id').references(() => students.id, { onDelete: 'set null' }),
    universityId: uuid('university_id').references(() => universities.id, { onDelete: 'set null' }),
    programId: uuid('program_id').references(() => programs.id, { onDelete: 'set null' }),
    status: applicationStatus('status').notNull().default('draft'),
    notes: text('notes'),
    intakeYear: integer('intake_year'),
    intakeMonth: text('intake_month'),
    transcriptUrl: text('transcript_url'),
    passportUrl: text('passport_url'),
    sopUrl: text('sop_url'),
    cvUrl: text('cv_url'),
    additionalDocs: jsonb('additional_docs').default(sql`'[]'::jsonb`),
    englishTestUrl: text('english_test_url'),
    englishTestType: text('english_test_type'),
    englishTestScore: text('english_test_score'),
    financialProofUrl: text('financial_proof_url'),
    adminNotes: text('admin_notes'),
    reviewedBy: text('reviewed_by'),
    reviewedAt: timestamp('reviewed_at', { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    currentStep: integer('current_step').default(1),
    progressPercent: integer('progress_percent').default(0),
    representativeName: text('representative_name'),
    representativeEmail: text('representative_email'),
    representativePhone: text('representative_phone'),
    representativeAddress: text('representative_address'),
    representativeCity: text('representative_city'),
    representativeState: text('representative_state'),
    representativeZip: text('representative_zip'),
    representativeCountry: text('representative_country'),
    englishProficiencyMethod: text('english_proficiency_method'),
    englishTestName: text('english_test_name'),
    englishTrfNumber: text('english_trf_number'),
    englishTestDate: text('english_test_date'),
    englishOverallScore: text('english_overall_score'),
    fundingSource: text('funding_source'),
    scholarshipReleaseAuth: text('scholarship_release_auth'),
    applicantSignature: text('applicant_signature'),
    signatureDate: text('signature_date'),
    termsAccepted: boolean('terms_accepted').notNull().default(false),
    submissionReference: text('submission_reference'),
    submittedAt: timestamp('submitted_at', { withTimezone: true }),
    submissionSnapshot: jsonb('submission_snapshot'),
    noWorkExperience: boolean('no_work_experience').notNull().default(false),
    noWorkExperienceExplanation: text('no_work_experience_explanation'),
  },
  (t) => [
    index('applications_agent_idx').on(t.agentId),
    index('applications_status_idx').on(t.status),
    index('applications_student_idx').on(t.studentId),
    index('applications_university_idx').on(t.universityId),
    index('applications_created_idx').on(t.createdAt),
    uniqueIndex('applications_reference_key').on(t.submissionReference),
  ],
)

